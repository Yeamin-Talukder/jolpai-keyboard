#!/usr/bin/perl
# Downloads Material Symbols (Rounded, weight 400, 24 px) from Google Fonts and writes them as
# Android vector drawables into keyboard-ui/src/main/res/drawable/ms_<name>[_fill].xml.
#
# Material Symbols are licensed under the Apache License 2.0 (see keyboard-ui/NOTICE.txt).
# Run from the project root:  perl tools/prepare-icons.pl
# The icons are listed below; "name:fill" also fetches the filled variant.
use strict;
use warnings;

my @icons = qw(
    shift shift:fill shift_lock:fill backspace keyboard_return arrow_forward search send
    keyboard_tab keyboard_tab_rtl check language mood content_paste mic edit_note settings lock
    chevron_left chevron_right open_in_full dock_to_bottom drag_handle grid_view
    arrow_back keyboard translate spellcheck palette height vibration toolbar add_reaction
    shield backup info check_circle:fill menu_book short_text delete add push_pin push_pin:fill
    folder content_copy upload download close edit dark_mode light_mode auto_awesome swipe
    gif_box image volume_up text_fields keyboard_keys history tune format_size restart_alt
    expand_more open_in_new done_all brightness_auto arrow_upward arrow_downward visibility
    visibility_off key record_voice_over space_bar lightbulb block schedule front_hand
    picture_in_picture 123 settings_backup_restore description save drag_pan
    link call mail password home code chat signature quickreply notes content_cut
    swipe_up swipe_down swipe_left swipe_right touch_long touch_double gesture keyboard_capslock
    expand_less close_fullscreen stop mic:fill drag_indicator rotate_90_degrees_ccw
    swap_horiz g_translate
);

my $out = 'keyboard-ui/src/main/res/drawable';
-d $out or mkdir $out or die "mkdir $out: $!";
my $base = 'https://fonts.gstatic.com/s/i/short-term/release/materialsymbolsrounded';

for my $spec (@icons) {
    my ($name, $fill) = split /:/, $spec;
    my @variants = (['default', "ms_$name"]);
    push @variants, ['fill1', "ms_${name}_fill"] if $fill;
    @variants = (['fill1', "ms_${name}_fill"]) if $fill && $name =~ /^(shift_lock|check_circle)$/;
    for my $v (@variants) {
        my ($style, $file) = @$v;
        my $svg = `curl -sS -m 30 "$base/$name/$style/24px.svg"`;
        die "download failed: $name/$style\n" unless $svg =~ /<svg/;
        my @paths = $svg =~ /<path[^>]*\bd="([^"]+)"/g;
        die "no paths in $name/$style\n" unless @paths;
        my ($vx, $vy, $vw, $vh) = $svg =~ /viewBox="(-?[\d.]+)\s+(-?[\d.]+)\s+([\d.]+)\s+([\d.]+)"/;
        die "no viewBox in $name/$style\n" unless defined $vh;
        open my $fh, '>', "$out/$file.xml" or die "$file: $!";
        print $fh qq{<?xml version="1.0" encoding="utf-8"?>\n};
        print $fh qq{<!-- Material Symbols Rounded "$name" ($style), Apache License 2.0. Generated by tools/prepare-icons.pl -->\n};
        print $fh qq{<vector xmlns:android="http://schemas.android.com/apk/res/android"\n};
        print $fh qq{    android:width="24dp"\n    android:height="24dp"\n};
        print $fh qq{    android:viewportWidth="$vw"\n    android:viewportHeight="$vh">\n};
        print $fh qq{    <group android:translateX="} . (-$vx) . qq{" android:translateY="} . (-$vy) . qq{">\n};
        print $fh qq{        <path\n            android:fillColor="#FFFFFFFF"\n            android:pathData="$_" />\n} for @paths;
        print $fh qq{    </group>\n</vector>\n};
        close $fh;
        print "$file\n";
    }
}
